// The completion script for each shell. Verbs, subcommands and flags come from
// the registry (completion/spec.ts) and are embedded, so they complete with no
// process start; positional values (check names, slice ids, workspaces, fixed
// words such as `create|release`) come from `workit __complete <words…>`.
import { staticTable } from "./spec";

export const SHELLS = ["zsh", "bash", "fish", "powershell"] as const;
export type Shell = (typeof SHELLS)[number];

/** The first line after the shebang or `#compdef`: marks a file Workit wrote. */
export const COMPLETION_MARKER = "# workit-owned-completion";

const header = (shell: Shell, version: string): string =>
  `${COMPLETION_MARKER}: generated by \`workit completion ${shell}\` (workit ${version}); do not edit.`;

/** `"key") printf '%s\n' w1 w2 ;;` per table row, for a POSIX-like `case`. */
const caseRows = (indent: string): string =>
  [...staticTable()]
    .map(([key, words]) => `${indent}"${key}") printf '%s\\n' ${words.join(" ")} ;;`)
    .join("\n");

function bash(version: string): string {
  return `${header("bash", version)}
_workit_static() {
  case "$1" in
${caseRows("    ")}
  esac
}

# Each line read is one literal candidate: never word-split, globbed or expanded
# (compgen -W would expand a candidate such as $(cmd)).
_workit_reply() {
  local line
  COMPREPLY=()
  while IFS= read -r line; do
    [[ -n $line && $line == "$1"* ]] && COMPREPLY+=("$line")
  done
}

_workit() {
  local cur="\${COMP_WORDS[COMP_CWORD]}" verb="" sub="" word skip="" i
  for ((i = 1; i < COMP_CWORD; i++)); do
    word="\${COMP_WORDS[i]}"
    if [[ -n $skip ]]; then skip=""; continue; fi
    case "$word" in
      --cwd | --session) skip=1 ;;
      -*) ;;
      *)
        if [[ -z $verb ]]; then verb="$word"
        elif [[ -z $sub && -n "$(_workit_static "$verb")" ]]; then sub="$word"; fi
        ;;
    esac
  done
  local key="$verb\${sub:+ $sub}"
  if [[ $cur == -* ]]; then
    _workit_reply "$cur" < <(_workit_static "-$key")
  elif [[ -z $verb ]]; then
    _workit_reply "$cur" < <(_workit_static "")
  elif [[ -z $sub && -n "$(_workit_static "$verb")" ]]; then
    _workit_reply "$cur" < <(_workit_static "$verb")
  else
    _workit_reply "$cur" < <(workit __complete "\${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null)
  fi
}

complete -F _workit workit
`;
}

function zsh(version: string): string {
  return `#compdef workit
${header("zsh", version)}
_workit_static() {
  case "$1" in
${caseRows("    ")}
  esac
}

_workit() {
  local cur="\${words[CURRENT]}" verb="" sub="" word skip="" i
  local -a cands
  for (( i = 2; i < CURRENT; i++ )); do
    word="\${words[i]}"
    if [[ -n $skip ]]; then skip=""; continue; fi
    case "$word" in
      --cwd|--session) skip=1 ;;
      -*) ;;
      *)
        if [[ -z $verb ]]; then verb="$word"
        elif [[ -z $sub && -n "$(_workit_static "$verb")" ]]; then sub="$word"; fi
        ;;
    esac
  done
  local key="$verb\${sub:+ $sub}"
  if [[ $cur == -* ]]; then
    cands=("\${(@f)$(_workit_static "-$key")}")
  elif [[ -z $verb ]]; then
    cands=("\${(@f)$(_workit_static "")}")
  elif [[ -z $sub && -n "$(_workit_static "$verb")" ]]; then
    cands=("\${(@f)$(_workit_static "$verb")}")
  else
    cands=("\${(@f)$(workit __complete "\${(@)words[2,CURRENT]}" 2>/dev/null)}")
  fi
  cands=("\${(@)cands:#}")
  compadd -a cands
}

if [[ "\${funcstack[1]}" == "_workit" ]]; then
  _workit "$@"
else
  compdef _workit workit
fi
`;
}

function fish(version: string): string {
  const rows = [...staticTable()]
    .map(([key, words]) => `        case '${key}'\n            printf '%s\\n' ${words.join(" ")}`)
    .join("\n");
  return `${header("fish", version)}
function __workit_static
    switch $argv[1]
${rows}
    end
end

function __workit_complete
    set -l typed (commandline -opc)
    set -l cur (commandline -ct)
    set -l verb ''
    set -l sub ''
    set -l skip 0
    for word in $typed[2..-1]
        if test $skip = 1
            set skip 0
            continue
        end
        switch $word
            case --cwd --session
                set skip 1
            case '-*'
            case '*'
                set -l subs (__workit_static $verb)
                if test -z "$verb"
                    set verb $word
                else if test -z "$sub"; and test (count $subs) -gt 0
                    set sub $word
                end
        end
    end
    set -l key $verb
    test -n "$sub"; and set key "$verb $sub"
    set -l subs (__workit_static $verb)
    if string match -q -- '-*' $cur
        __workit_static "-$key"
    else if test -z "$verb"
        __workit_static ''
    else if test -z "$sub"; and test (count $subs) -gt 0
        printf '%s\\n' $subs
    else
        workit __complete $typed[2..-1] $cur 2>/dev/null
    end
end

complete -c workit -f -a '(__workit_complete)'
`;
}

function powershell(version: string): string {
  return `${header("powershell", version)}
Register-ArgumentCompleter -Native -CommandName workit -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $typed = @($commandAst.CommandElements |
        Where-Object { $_.Extent.EndOffset -le $cursorPosition } |
        Select-Object -Skip 1 |
        ForEach-Object { $_.ToString() })
    if ($wordToComplete -eq '') { $typed += '' }
    & workit __complete @typed 2>$null | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
`;
}

/** The completion script for `shell`. */
export function completionScript(shell: Shell, version: string): string {
  if (shell === "bash") return bash(version);
  if (shell === "zsh") return zsh(version);
  if (shell === "fish") return fish(version);
  return powershell(version);
}
